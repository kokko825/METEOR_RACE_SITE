import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.TEST_ORIGIN || 'http://localhost:3001';
assert.ok(['localhost','127.0.0.1'].includes(new URL(origin).hostname));
const browser = await chromium.launch({headless:true, ...(process.env.TEST_BROWSER_PATH ? {executablePath:process.env.TEST_BROWSER_PATH} : {})});
try {
  for (const width of [320,390,768,1440]) for (const language of ['ja','en']) {
    const page = await browser.newPage({viewport:{width,height:900}});
    page.setDefaultTimeout(20000);
    const errors=[];
    page.on('pageerror', e=>errors.push(e.message));
    await page.route('**/api/profile',route=>route.fulfill({json:{synced:false}}));
    await page.addInitScript(lang=>localStorage.setItem('meteor-race-language',lang),language);
    await page.goto(origin);
    await page.locator('.title-start').waitFor();
    await page.waitForTimeout(700);
    await page.locator('.hud-player').click();
    await page.locator('.settings-drawer').waitFor();
    await page.waitForTimeout(50);
    assert.ok(await page.locator('.settings-drawer .icon-close').evaluate(el=>el===document.activeElement));
    await page.keyboard.press('Shift+Tab');
    assert.ok(await page.locator('.settings-drawer').evaluate(el=>el.contains(document.activeElement)), 'Tab remains in modal');
    await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new Error('Denied'))}}));
    await page.locator('.copy-button').click();
    await page.waitForTimeout(50);
    assert.match(await page.locator('.copy-button').innerText(), language==='ja'?/できません/:/FAILED/);
    let sent=0, release;
    const gate=new Promise(resolve=>{release=resolve;});
    await page.route('**/api/contact',async route=>{sent++;await gate;await route.fulfill({json:{reference:'TEST'}});});
    const message=page.locator('.settings-drawer textarea');
    await message.fill('Local test message, not sent externally.');
    await page.locator('.contact-send').click();
    assert.ok(await page.locator('.contact-send').isDisabled());
    await message.fill('New draft while the request is pending.');
    release();
    await page.waitForFunction(()=>!document.querySelector('.contact-send')?.disabled);
    assert.equal(sent,1);
    assert.equal(await message.inputValue(),'New draft while the request is pending.');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Settings has no horizontal overflow');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.settings-drawer').count(),0);
    assert.ok(await page.locator('.hud-player').evaluate(el=>el===document.activeElement),'Focus returns to settings trigger');
    await page.locator('.title-manual').click();
    await page.locator('.manual-drawer').waitFor();
    assert.equal(await page.locator('.manual-item-grid .clean-icon svg').count(),6,'Rules use the six current equipment icons');
    await page.keyboard.press('Shift+Tab');
    assert.ok(await page.locator('.manual-drawer').evaluate(el=>el.contains(document.activeElement)));
    await page.locator('.manual-tabs button').last().click();
    assert.equal(await page.locator('.authorized-equipment .clean-icon svg').count(),6,'Equipment sources use the same icons');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    if(process.env.LAYOUT_SCREENSHOT_DIR) await page.screenshot({path:`${process.env.LAYOUT_SCREENSHOT_DIR}/manual-${width}-${language}.png`});
    await page.locator('.authorized-equipment article').first().scrollIntoViewIfNeeded();
    assert.ok(await page.locator('.authorized-equipment article p').first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize)>=14));
    if(process.env.LAYOUT_SCREENSHOT_DIR) await page.screenshot({path:`${process.env.LAYOUT_SCREENSHOT_DIR}/equipment-${width}-${language}.png`});
    await page.keyboard.press('Escape');
    await page.locator('.title-beginner').click();
    await page.locator('.tutorial-confirm').waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.tutorial-confirm').count(),0);
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.waitForTimeout(50);
    assert.ok(await page.locator('.shell').evaluate(el=>el.classList.contains('reduced-motion')));
    assert.deepEqual(errors,[]);
    await page.close();
  }
  const blocked = await browser.newPage();
  const errors=[];
  blocked.on('pageerror',e=>errors.push(e.message));
  await blocked.route('**/api/profile',route=>route.fulfill({status:503,json:{error:'offline'}}));
  await blocked.addInitScript(()=>{
    Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Disabled','SecurityError');}});
  });
  await blocked.goto(origin);
  await blocked.locator('.title-start').waitFor();
  await blocked.waitForTimeout(700);
  await blocked.locator('.title-start').click();
  await blocked.locator('.entry-confirm').click();
  await blocked.locator('.entry-confirm').waitFor();
  assert.deepEqual(errors,[], 'Storage-denied browser can navigate');
  await blocked.close();
  const doc=await browser.newPage();
  await doc.addInitScript(()=>{
    window.preferenceWrites=0;
    const write=Storage.prototype.setItem;
    Storage.prototype.setItem=function(...args){window.preferenceWrites++;return write.apply(this,args);};
  });
  await doc.goto(`${origin}/updates`);
  await doc.waitForTimeout(700);
  assert.equal(await doc.evaluate(()=>window.preferenceWrites),0,'Reading updates must not rewrite game preferences');
  await doc.evaluate(()=>{localStorage.setItem('meteor-race-language','en');dispatchEvent(new StorageEvent('storage',{key:'meteor-race-language'}));});
  await doc.waitForFunction(()=>document.documentElement.lang==='en');
  await doc.close();
  console.log('PASS: dialogs, clipboard denial, live motion preference at 4 widths × 2 languages; storage denied navigation');
} finally {await browser.close();}
