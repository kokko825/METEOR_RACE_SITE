/** Refresh the self-hosted OFL-licensed Japanese font from Google's official distribution. */
import fs from "node:fs/promises";
import path from "node:path";

const directory = path.resolve("public/assets/fonts/noto-sans-jp");
const cssUrl = "https://fonts.googleapis.com/css2?family=Noto+Sans+JP:wght@400..800&display=swap";
const response = await fetch(cssUrl, { headers: {
  "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
} });
if (!response.ok) throw new Error(`Font stylesheet: ${response.status}`);
let css = await response.text();
const urls = [...new Set([...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/g)].map(match => match[1]))];
if (!urls.length) throw new Error("Expected WOFF2 font subsets");
await fs.mkdir(directory, { recursive: true });
for (let offset = 0; offset < urls.length; offset += 6) {
  await Promise.all(urls.slice(offset, offset + 6).map(async (url, index) => {
    const name = `subset-${String(offset + index).padStart(3, "0")}.woff2`;
    const font = await fetch(url);
    if (!font.ok) throw new Error(`Font download: ${font.status}`);
    await fs.writeFile(path.join(directory, name), Buffer.from(await font.arrayBuffer()));
    css = css.replaceAll(url, `/assets/fonts/noto-sans-jp/${name}`);
  }));
}
const license = await fetch("https://raw.githubusercontent.com/google/fonts/main/ofl/notosansjp/OFL.txt");
if (!license.ok) throw new Error(`Font license: ${license.status}`);
await fs.writeFile(path.join(directory, "OFL.txt"), (await license.text()).replace(/[ \t]+$/gm, ""));
await fs.writeFile(path.resolve("app/styles/japanese-font.css"), `/* Generated by scripts/sync-japanese-font.mjs. Noto Sans JP, SIL OFL 1.1. */\n${css}`);
console.log(`Self-hosted Japanese font: ${urls.length} Unicode subsets; browsers load only required subsets.`);
